#!/usr/bin/env python3
"""Prepare new bounded native QA state; never launches a GUI or a background service."""
from pathlib import Path
import hashlib,json,os,py_compile,shutil,stat,time
repo=Path(__file__).resolve().parents[1]
root=repo/'build/native-acceptance/runtime'
if root.exists():raise SystemExit('Refusing existing runtime. Preserve it; do not overwrite fixtures/profile.')
monitor=repo/'build/MacBook Storage Monitor.app/Contents/MacOS/StorageMonitor'
if not monitor.is_file():raise SystemExit('Build monitor with scripts/build.sh first')
root.mkdir(mode=0o700,parents=True)
for rel in ['ApplicationSupport','ApplicationSupport/inventory-requests','fixtures','Caches','Logs','Temporary','bin']:(root/rel).mkdir(mode=0o700)
helper=root/'bin/StorageMonitor';shutil.copyfile(monitor,helper);helper.chmod(0o700)
for rel in ['ApplicationSupport/history.sqlite3','Logs/viewer.log','Logs/worker.log','Logs/worker-errors.log']:(root/rel).touch(mode=0o600)
items={
'ordinary-operator-qa.txt':b'Disposable Storage Monitor ordinary text fixture.\n',
'small-directory/readme.txt':b'Disposable small directory.\n',
'nested-directory/child/deep.txt':b'Disposable nested directory.\n',
'file with spaces operator QA.txt':b'Disposable filename with spaces.\n',
'caf\u00e9-\u732b-operator-QA.txt':b'Disposable Unicode filename.\n',
'checksum-operator-qa.txt':b'Storage Monitor native QA checksum fixture.\n',
'historical-looking/archive-old-2020.txt':b'Naming and age alone do not imply cleanup safety.\n',
'generated-project/module.py':b'value = 42\n',
}
for rel,body in items.items():
 p=root/'fixtures'/rel;p.parent.mkdir(parents=True,exist_ok=True,mode=0o700);p.write_bytes(body);p.chmod(0o600)
source=root/'fixtures/generated-project/module.py';cache=source.parent/'__pycache__';cache.mkdir(mode=0o700)
py_compile.compile(str(source),cfile=str(cache/'module.cpython-qa.pyc'),doraise=True)
(cache/'module.cpython-qa.pyc').chmod(0o600)
def identity(p,authorized=False):
 s=p.lstat();return {'path':str(p),'device':s.st_dev,'inode':s.st_ino,'kind':'directory' if stat.S_ISDIR(s.st_mode) else 'file','authorized':authorized}
registered=[]
for p in sorted((root/'fixtures').rglob('*')):
 if p.is_symlink():raise SystemExit('Unexpected fixture symlink')
 registered.append(identity(p,True))
profile={'version':1,'root':identity(root),'catalog':identity(root/'ApplicationSupport/history.sqlite3'),'createdAt':time.time(),'helperSHA256':hashlib.sha256(helper.read_bytes()).hexdigest(),'fixtures':registered}
(root/'profile.json').write_text(json.dumps(profile,indent=2,ensure_ascii=False)+'\n');(root/'profile.json').chmod(0o600)
manifest={'fixture_root':str(root/'fixtures'),'native_observations':'UNVERIFIED','protected_representation':'Existing model tests only; no fake system/credential files','items':[]}
for row in registered:
 p=Path(row['path']);manifest['items'].append({**row,'sha256':hashlib.sha256(p.read_bytes()).hexdigest() if p.is_file() else None,'expected_classification':'Generated bytecode may qualify for review; actual evidence required' if p.suffix=='.pyc' else 'Ordinary or historical-looking representation; name alone is not cleanup evidence','expected_trash':'Only this exact registered filesystem identity may reach normal Trash safety preflight'})
(root/'fixtures-manifest.json').write_text(json.dumps(manifest,indent=2,ensure_ascii=False)+'\n');(root/'fixtures-manifest.json').chmod(0o600)
launch=repo/'build/native-acceptance/launch-qa.sh'
import shlex
exe=root/'Storage Monitor QA.app/Contents/MacOS/StorageMonitorViewer'
launch.write_text('#!/bin/sh\nset -eu\n# Operator action only. Explicit profile is checked before any native window exists.\nexec /usr/bin/env -i PATH=/usr/bin:/bin:/usr/sbin:/sbin TMPDIR='+shlex.quote(str(root/'Temporary')+'/')+' SQLITE_TMPDIR='+shlex.quote(str(root/'Temporary'))+' '+shlex.quote(str(exe))+' --qa-runtime-root '+shlex.quote(str(root))+'\n');launch.chmod(0o700)
print(json.dumps({'root':str(root),'registrations':len(registered),'launcher':str(launch),'native_launched':False}))
